require 'test.globals'
require 'src.util.Bitset'

Describe('Bitset', function ()
    Test('new', function ()
        local sut = Bitset.new(4)
        Expect(sut:get(1)).toBe(false)
        Expect(sut:get(2)).toBe(false)
        Expect(sut:get(3)).toBe(false)
        Expect(sut:get(4)).toBe(false)
        Expect(sut:get(5)).toBe(nil)
    end)

    Test('set and get', function ()
        local sut = Bitset.new(4)
        sut:set(2)
        Expect(sut:get(2)).toBe(true)
        sut:set(2)
        Expect(sut:get(2)).toBe(false)
    end)

    Test('equals', function ()
        local sut = Bitset.new(4)
        local other = Bitset.new(4)
        Expect(sut:equals(other)).toBe(true)
        other:set(1)
        Expect(sut:equals(other)).toBe(false)
    end)

    Test('bitwiseAnd', function ()
        local sut = Bitset.new(3)
        sut:set(2)
        sut:set(3)
        local other = Bitset.new(3)
        other:set(2)
        local bitwiseAnd = sut:bitwiseAnd(other)
        Expect(bitwiseAnd:equals(other)).toBe(true)
    end)
end)