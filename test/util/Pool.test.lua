require 'test.globals'
require 'src.util.Pool'

Describe('Pool', function ()
    Test('new', function ()
        local sut = Pool.new(2)
        Expect(sut:get(1)).toBe(nil)
        Expect(sut:get(2)).toBe(nil)
        Expect(sut:get(3)).toBe(nil)
    end)

    Test('insert', function ()
        local sut = Pool.new(10)
        sut:insert(10)
        sut:insert(20)
        Expect(sut:get(1)).toBe(10)
        Expect(sut:get(2)).toBe(20)
    end)

    Test('remove', function ()
        local sut = Pool.new(10)
        sut:insert(10)
        sut:insert(20)
        sut:insert(30)
        sut:remove(2)
        Expect(sut:get(1)).toBe(10)
        Expect(sut:get(2)).toBe(30)
        Expect(sut:get(3)).toBe(nil)
    end)

    Test('set', function ()
        local sut = Pool.new(10)
        sut:set(3, 'hello')
        Expect(sut:get(3)).toBe('hello')
        Expect(sut:get(1)).toBe(nil)
    end)
end)